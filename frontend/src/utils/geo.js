export function getAreaNetworkIntelligence(lat, lng) {
  if (lat === undefined || lng === undefined || isNaN(lat) || isNaN(lng)) {
    lat = 5.6037;
    lng = -0.1870;
  }

  let closest = GHANA_TELECOM_INTELLIGENCE_NODES[0];
  let minDistance = Infinity;

  for (const item of GHANA_TELECOM_INTELLIGENCE_NODES) {
    const dist = getDistanceKm(lat, lng, item.lat, item.lng);
    if (dist < minDistance) {
      minDistance = dist;
      closest = item;
    }
  }

  return {
    townName: closest.name,
    distanceKm: parseFloat(minDistance.toFixed(1)),
    mtn: closest.mtn,
    telecel: closest.telecel,
    at: closest.at
  };
}

// Ultra-fast instant IP Geolocation Engine
export async function fetchInstantIpLocation() {
  try {
    const res = await fetch('https://freeipapi.com/api/json', { cache: 'no-store' });
    const data = await res.json();
    if (data && typeof data.latitude === 'number' && typeof data.longitude === 'number') {
      return {
        lat: data.latitude,
        lng: data.longitude,
        cityName: data.cityName || 'Ghana',
        regionName: data.regionName || 'Ghana',
        countryName: data.countryName || 'Ghana',
        isIp: true,
      };
    }
  } catch {
    try {
      const res2 = await fetch('https://ipapi.co/json/', { cache: 'no-store' });
      const data2 = await res2.json();
      if (data2 && typeof data2.latitude === 'number' && typeof data2.longitude === 'number') {
        return {
          lat: data2.latitude,
          lng: data2.longitude,
          cityName: data2.city || 'Ghana',
          regionName: data2.region || 'Ghana',
          countryName: data2.country_name || 'Ghana',
          isIp: true,
        };
      }
    } catch {
      // Ignore
    }
  }
  return null;
}

// Haversine formula for exact distance in meters
export function getDistanceMeters(lat1, lon1, lat2, lon2) {
  if (typeof lat1 !== 'number' || typeof lon1 !== 'number' || typeof lat2 !== 'number' || typeof lon2 !== 'number') {
    return 0;
  }
  const R = 6371000;
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c);
}

// Haversine formula for exact distance in KM
export function getDistanceKm(lat1, lon1, lat2, lon2) {
  const meters = getDistanceMeters(lat1, lon1, lat2, lon2);
  return meters / 1000;
}

// Find closest deep micro-locality fallback
export function findNearestMicroLocality(lat, lng) {
  let closest = null;
  let minMeters = Infinity;

  for (const item of GHANA_MICRO_LOCALITIES) {
    const meters = getDistanceMeters(lat, lng, item.lat, item.lng);
    if (meters < minMeters) {
      minMeters = meters;
      closest = item;
    }
  }

  if (closest && minMeters <= 8000) {
    return {
      landmark: closest.name,
      suburb: closest.suburb,
      district: closest.district,
      distanceMeters: minMeters,
    };
  }

  return {
    landmark: `GPS Coordinates (${lat.toFixed(5)}, ${lng.toFixed(5)})`,
    suburb: `Ghana (${lat.toFixed(3)}, ${lng.toFixed(3)})`,
    district: 'Ghana',
    distanceMeters: 0,
  };
}

// Deep Multi-API Reverse Geocoding with Street & Building Level Precision
export async function reverseGeocodeGhanaDeep(lat, lng) {
  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lng}&zoom=19&addressdetails=1`,
      { headers: { 'User-Agent': 'NetworkRadarGhana/2.0' } }
    );
    const data = await res.json();
    const addr = data?.address || {};

    const street =
      addr.road ||
      addr.street ||
      addr.pedestrian ||
      addr.path ||
      addr.footway ||
      addr.amenity ||
      addr.building ||
      addr.commercial ||
      addr.shop;

    const suburb =
      addr.suburb ||
      addr.neighbourhood ||
      addr.residential ||
      addr.quarter ||
      addr.village ||
      addr.city_district ||
      addr.town;

    const city = addr.city || addr.town || addr.county || 'Ghana';
    const district = addr.county || addr.state_district || addr.state || city;

    if (street || suburb) {
      const landmarkText = street
        ? suburb
          ? `${street}, ${suburb}`
          : `${street}, ${city}`
        : `${suburb}, ${city}`;

      return {
        landmark: landmarkText,
        suburb: suburb || city,
        district: district,
        fullAddress: data.display_name,
        confidence: 'HIGH_GPS_PRECISION',
      };
    }
  } catch {
    // Fallback to local deep micro-locality matching
  }

  const fallback = findNearestMicroLocality(lat, lng);
  return {
    landmark: fallback.landmark,
    suburb: fallback.suburb,
    district: fallback.district,
    fullAddress: `${fallback.landmark}, ${fallback.district}`,
    confidence: 'MICRO_LOCALITY_MATCH',
  };
}
